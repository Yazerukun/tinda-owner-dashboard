-- tinda-sync D1 Database Migration v1
-- Run: wrangler d1 execute tinda-sync-db --remote --file=migrations/0001_init.sql

-- Owner accounts (the boss who monitors sales)
CREATE TABLE IF NOT EXISTS owner_users (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  password_salt TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Each TINDA-POS installation (one per branch/PC)
CREATE TABLE IF NOT EXISTS stores (
  id TEXT PRIMARY KEY,                          -- UUID generated by TINDA-POS app
  branch_name TEXT NOT NULL,                    -- from TINDA-POS Settings.store_name
  sync_key_hash TEXT NOT NULL,                  -- sha256(sync_key + ':' + SESSION_SECRET)
  owner_user_id INTEGER REFERENCES owner_users(id) ON DELETE SET NULL,
  last_sale_at TEXT,                            -- last sale synced time
  last_sync_at TEXT,                            -- last any sync time
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Individual completed sales (synced per-checkout from TINDA-POS)
CREATE TABLE IF NOT EXISTS sales (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  store_id TEXT NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
  local_sale_id INTEGER NOT NULL,               -- sales.id in TINDA-POS SQLite
  transaction_no TEXT NOT NULL,
  cashier_name TEXT,
  customer_name TEXT,
  subtotal_c INTEGER NOT NULL DEFAULT 0,
  discount_c INTEGER NOT NULL DEFAULT 0,
  total_c INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'COMPLETED',     -- COMPLETED/VOIDED/REFUNDED
  cash_c INTEGER NOT NULL DEFAULT 0,
  gcash_c INTEGER NOT NULL DEFAULT 0,
  maya_c INTEGER NOT NULL DEFAULT 0,
  utang_c INTEGER NOT NULL DEFAULT 0,
  local_shift_id INTEGER,
  sold_at TEXT NOT NULL,                        -- original TINDA-POS created_at
  synced_at TEXT NOT NULL DEFAULT (datetime('now')),
  UNIQUE(store_id, local_sale_id)
);
CREATE INDEX IF NOT EXISTS idx_sales_store ON sales(store_id);
CREATE INDEX IF NOT EXISTS idx_sales_date ON sales(sold_at);
CREATE INDEX IF NOT EXISTS idx_sales_store_date ON sales(store_id, sold_at);

-- Line items per sale
CREATE TABLE IF NOT EXISTS sale_items (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  sale_id INTEGER NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
  product_name TEXT NOT NULL,
  unit_name TEXT NOT NULL,
  qty REAL NOT NULL DEFAULT 1,                  -- supports decimal (weighable)
  unit_price_c INTEGER NOT NULL,
  subtotal_c INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sale_items_sale ON sale_items(sale_id);

-- Inventory/stock movements (synced from inventory_movements table in TINDA-POS)
CREATE TABLE IF NOT EXISTS stock_movements (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  store_id TEXT NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
  local_movement_id INTEGER NOT NULL,           -- inventory_movements.id in TINDA-POS
  product_name TEXT NOT NULL,
  movement_type TEXT NOT NULL,                  -- SALE/RESTOCK/PURCHASE/ADJUSTMENT/REFUND/etc
  quantity_change REAL NOT NULL,                -- negative = stock out, positive = stock in
  quantity_before REAL NOT NULL,
  quantity_after REAL NOT NULL,
  unit TEXT NOT NULL DEFAULT 'piece',
  reference TEXT,                               -- transaction_no if linked to a sale
  reason TEXT,
  moved_at TEXT NOT NULL,                       -- original TINDA-POS created_at
  synced_at TEXT NOT NULL DEFAULT (datetime('now')),
  UNIQUE(store_id, local_movement_id)
);
CREATE INDEX IF NOT EXISTS idx_movements_store ON stock_movements(store_id);
CREATE INDEX IF NOT EXISTS idx_movements_date ON stock_movements(moved_at);
CREATE INDEX IF NOT EXISTS idx_movements_product ON stock_movements(store_id, product_name);

-- Shift close snapshots (summary per shift per cashier)
CREATE TABLE IF NOT EXISTS shift_snapshots (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  store_id TEXT NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
  local_shift_id INTEGER NOT NULL,
  cashier_name TEXT NOT NULL,
  shift_date TEXT NOT NULL,                     -- YYYY-MM-DD
  opened_at TEXT NOT NULL,
  closed_at TEXT NOT NULL,
  gross_sales_c INTEGER NOT NULL DEFAULT 0,
  cash_c INTEGER NOT NULL DEFAULT 0,
  gcash_c INTEGER NOT NULL DEFAULT 0,
  maya_c INTEGER NOT NULL DEFAULT 0,
  utang_c INTEGER NOT NULL DEFAULT 0,
  refund_total_c INTEGER NOT NULL DEFAULT 0,
  void_count INTEGER NOT NULL DEFAULT 0,
  transaction_count INTEGER NOT NULL DEFAULT 0,
  expenses_c INTEGER NOT NULL DEFAULT 0,
  net_sales_c INTEGER NOT NULL DEFAULT 0,
  synced_at TEXT NOT NULL DEFAULT (datetime('now')),
  UNIQUE(store_id, local_shift_id)
);
CREATE INDEX IF NOT EXISTS idx_shifts_store ON shift_snapshots(store_id);
CREATE INDEX IF NOT EXISTS idx_shifts_date ON shift_snapshots(shift_date);

-- Owner login sessions
CREATE TABLE IF NOT EXISTS owner_sessions (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  owner_user_id INTEGER NOT NULL REFERENCES owner_users(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX IF NOT EXISTS idx_sessions_token ON owner_sessions(token_hash);
